import { test, expect } from '@playwright/test'
import { loadFixture, login } from './fixture.js'

test('new patient and fetal visit flow preserves report through audit and completion', async ({ browser }) => {
  const info = await loadFixture()
  const context = await browser.newContext()
  context.setDefaultTimeout(8000)
  const page = await context.newPage()
  await login(page, 'l1', info.password)
  await page.goto('/patients/new')
  await page.locator('#newpatient-patient_id').fill(`SYNTH-${Date.now()}`)
  await page.locator('#newpatient-salutation').selectOption('Ms.')
  await page.locator('#newpatient-first_name').fill('Dummy')
  await page.locator('#newpatient-last_name').fill('Workflow')
  await page.locator('#newpatient-age').fill('30')
  await page.locator('input[name="gender"][value="F"]').check()
  await page.locator('#newpatient-street').fill('Test address')
  await page.locator('#newpatient-zip_code').fill('600001')
  await page.locator('#newpatient-state').selectOption('Tamil Nadu')
  await page.locator('#newpatient-district_city').selectOption('Chennai')
  await page.locator('#newpatient-phone1').fill('1234567890')
  await page.locator('#newpatient-family_doctor').selectOption('Self')
  await page.getByRole('button', { name: 'Save Patient' }).click()
  await page.waitForURL('**/visits?patient=*')
  const patientId = new URL(page.url()).searchParams.get('patient')
  await page.getByLabel('Visit date and time *').fill('2026-11-12T10:00')
  await page.getByLabel('Scan type *').selectOption('Fetal Echo')
  await expect(page.getByLabel('Report template *')).not.toHaveValue('')
  await page.getByRole('button', { name: 'Save & Go to Reporting' }).click()
  await expect(page).toHaveURL(/\/fetal-echo-report\?/)
  const visitId = new URL(page.url()).searchParams.get('visitId')
  await page.getByRole('button', { name: 'Save & next' }).click()
  await expect(page.getByRole('status')).toContainText('Enter LMP, EDD or embryo transfer date.')
  await expect(page.getByLabel('LMP', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('Number of fetuses')).toHaveClass(/border-red-500/)
  await page.getByRole('combobox', { name: 'Indication' }).fill('Synthetic indication')
  await page.getByLabel('LMP', { exact: true }).fill('2026-06-01')
  await page.getByLabel('Number of fetuses').selectOption('1')
  await page.getByRole('button', { name: 'Echo details', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Not saved.')
  await page.getByRole('button', { name: 'Save report', exact: true }).last().click()
  await expect(page.getByRole('status')).toContainText('Fetal echo report saved.')
  await page.getByRole('button', { name: 'Impression', exact: true }).click()
  await page.getByLabel('Header comments', { exact: false }).fill('Synthetic header')
  await page.getByLabel('Final impression', { exact: true }).fill('Synthetic final impression')
  await page.getByLabel('Disclaimer comments', { exact: false }).fill('Synthetic disclaimer')
  await page.getByLabel('Primary consultant').fill('Test consultant')
  await page.getByRole('button', { name: 'Save report', exact: true }).last().click()
  await expect(page.getByRole('status')).toContainText('Fetal echo report saved.')
  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(page.getByRole('article').getByText('Synthetic final impression', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close preview' }).click()
  const reportUrl = page.url()
  await context.close()

  const audit = await browser.newContext(); audit.setDefaultTimeout(8000); const auditor = await audit.newPage()
  await login(auditor, 'l2', info.password); await auditor.goto(reportUrl)
  await auditor.getByRole('button', { name: 'Impression', exact: true }).click()
  await auditor.getByLabel('Auditing done').check()
  await auditor.getByRole('button', { name: 'Save report', exact: true }).last().click()
  await expect(auditor.getByRole('status')).toContainText('Fetal echo report saved.')
  await audit.close()

  const final = await browser.newContext(); final.setDefaultTimeout(8000); const approver = await final.newPage()
  await login(approver, 'dr.shanthi', info.password); await approver.goto(reportUrl)
  await approver.getByRole('button', { name: 'Impression', exact: true }).click()
  await expect(approver.getByText('Audit: Done — L2 Dummy')).toBeVisible()
  await approver.getByLabel('Report completed', { exact: true }).check()
  await approver.getByRole('button', { name: 'Save report', exact: true }).last().click()
  await approver.getByRole('button', { name: 'Complete and lock' }).click()
  await expect(approver.getByRole('button', { name: 'Report locked' })).toBeDisabled()
  await approver.goto(`/visits?patient=${patientId}`)
  await approver.locator('tr', { hasText: 'Fetal Echo' }).first().click()
  await expect(approver).toHaveURL(new RegExp(`visitId=${visitId}`))
  await expect(approver.getByRole('button', { name: 'Report locked' })).toBeDisabled()
  await final.close()
})
